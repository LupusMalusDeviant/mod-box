function copyTree(from, to, report) {
  fs.mkdirSync(to, { recursive: true })
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, e.name)
    const d = path.join(to, e.name)
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name) || e.name === '.claude-plugin') continue
      if (['skills', 'agents', 'commands'].includes(e.name)) {
        report.push(t(`Ordner ${e.name}/ nicht übernommen: Skills, Agents und Befehlsdateien lassen sich nicht pro Mod schalten (das Plugin dafür normal per /plugin installieren).`, `Folder ${e.name}/ not taken over: skills, agents and command files cannot be switched per mod (install that plugin normally with /plugin).`))
        continue
      }
      copyTree(s, d, report)
    } else if (e.isFile()) {
      if (fs.statSync(s).size > 5 * 1024 * 1024) {
        report.push(t(`${e.name} nicht übernommen (größer als 5 MB).`, `${e.name} not taken over (larger than 5 MB).`))
        continue
      }
      if (/^(package-lock\.json|bun\.lockb?|yarn\.lock|pnpm-lock\.yaml)$/.test(e.name)) continue
      fs.copyFileSync(s, d)
    }
  }
}

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else out.push(p)
  }
  return out
}

function uniquePrefix(id, taken) {
  const parts = id.split(/[^a-z0-9]+/i).filter(Boolean)
  let base = parts.map(p => p[0]).join('').toLowerCase()
  if (base.length < 2) base = id.replace(/[^a-z0-9]/gi, '').slice(0, 3).toLowerCase()
  let p = base
  for (let i = 2; taken.has(p); i++) p = base + i
  return p
}

// Rewrites a mod's code for the box. Returns notes.
// `prefixes` maps every plugin name living in the box to its state prefix (its own
// included), so references to other box mods' state are translated too.
export function rewrite(code, { upstream, prefix, id, plugin, prefixes = {} }) {
  const notes = []
  const q = upstream.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const map = { ...prefixes, [upstream]: prefix }
  let n = 0
  // { plugin: 'name', key: 'x' } and { key: 'x', plugin: 'name' }
  code = code.replace(/plugin:\s*(['"])([\w@/.-]+)\1(\s*,\s*key:\s*)(['"])([\w$-]+)\4/g, (all, _q, name, mid, kq, key) => {
    if (!(name in map)) return all
    if (name === upstream) n++
    return `plugin: '${plugin}'${mid}${kq}${map[name]}_${key}${kq}`
  })
  code = code.replace(/key:\s*(['"])([\w$-]+)\1(\s*,\s*plugin:\s*)(['"])([\w@/.-]+)\4/g, (all, kq, key, mid, _q, name) => {
    if (!(name in map)) return all
    if (name === upstream) n++
    return `key: ${kq}${map[name]}_${key}${kq}${mid}'${plugin}'`
  })
  if (new RegExp(`plugin:\\s*['"]${q}['"]`).test(code)) notes.push(t(`Ein State-Verweis auf "${upstream}" hat eine ungewöhnliche Form und wurde nicht umgeschrieben.`, `A state reference to "${upstream}" has an unusual form and was not rewritten.`))
  for (const m of code.matchAll(/plugin:\s*['"]([\w@/.-]+)['"]\s*,\s*key:/g)) {
    if (m[1] !== plugin && !(m[1] in map)) notes.push(t(`Liest den State des Plugins "${m[1]}", das nicht in der Box ist; dieser Teil bleibt leer, solange es nicht separat installiert ist.`, `Reads the state of plugin "${m[1]}", which is not in the box; that part stays empty unless it is installed separately.`))
  }
  // Tools are named mcp__<plugin>__<name>
  code = code.replace(new RegExp(`mcp__${q}__`, 'g'), `mcp__${plugin}__`)
  // Files from the plugin folder now live under mods/<id>/
  code = code.replace(/(\$\.plugin\.root\s*\+\s*)(['"`])\//g, `$1$2/mods/${id}/`)
  code = code.replace(/\$\{\s*\$\.plugin\.root\s*\}\//g, `\${$.plugin.root}/mods/${id}/`)
  if (/\$\.plugin\.root(?!\s*\+\s*['"`]\/mods\/)(?!\s*\}\/mods\/)/.test(code)) notes.push(t('$.plugin.root wird in einer Form benutzt, die nicht automatisch umgeschrieben wurde; Pfade prüfen.', '$.plugin.root is used in a form that was not rewritten automatically; check the paths.'))
  // Several mods may watch the same event if each has a matcher: {} matches everything.
  code = code.replace(/(?<![\w.$])on\((['"][\w.*!]+['"]),(?!\s*\{)\s*/g, 'on($1, {}, ')
  return { code, notes, stateRefs: n }
}

function importMod(a) {
  let dir
  if (a.url.length) dir = fetchLink(a.url[0], a.refresh === true)
  else if (a.dir) dir = path.resolve(String(a.dir))
  else throw new Error(t('--dir oder --url angeben', 'pass --dir or --url'))

  // A marketplace: resolve the entry.
  let pluginDir = dir
  const mp = path.join(dir, '.claude-plugin', 'marketplace.json')
  if (a.plugin && fs.existsSync(mp)) {
    const entry = (readJson(mp).plugins ?? []).find(p => p.name === a.plugin)
    if (!entry) throw new Error(t(`Plugin ${a.plugin} steht nicht im Marketplace`, `plugin ${a.plugin} is not in the marketplace`))
    if (typeof entry.source === 'string') pluginDir = path.resolve(dir, entry.source)
    else {
      const r = remoteOf(entry.source)
      if (!r) throw new Error(t(`Quelle von ${a.plugin} wird nicht unterstützt`, `the source of ${a.plugin} is not supported`))
      pluginDir = fetchParsed({ clone: parseLink(r.link).clone, ref: r.ref, sub: (r.path ?? '').replace(/^\.?\/|\/$/g, '') }, a.refresh === true)
    }
  } else if (a.plugin) {
    const hit = findPlugins(dir).find(p => p.name === a.plugin)
    if (!hit) throw new Error(t(`Plugin ${a.plugin} nicht gefunden`, `plugin ${a.plugin} not found`))
    pluginDir = hit.dir
  } else {
    const all = findPlugins(dir)
    if (all.length !== 1) throw new Error(t(`${all.length} Plugins gefunden; --plugin <name> angeben`, `${all.length} plugins found; pass --plugin <name>`))
    pluginDir = all[0].dir
  }

  const info = pluginInfo(pluginDir)
  if (!info) throw new Error(t('Kein .claude-plugin/plugin.json gefunden', 'no .claude-plugin/plugin.json found'))
  if (!info.isMod) throw new Error(t(`${info.name} ist kein Mod mit Function-Hooks (hooks/hooks.json ohne "modules"); normal per /plugin installieren`, `${info.name} is not a mod with function hooks (hooks/hooks.json has no "modules"); install it normally with /plugin`))
  const manifest = readJson(path.join(pluginDir, '.claude-plugin', 'plugin.json'))
  const modules = readJson(path.join(pluginDir, 'hooks', 'hooks.json')).modules
  const report = []
  if (modules.length > 1) report.push(t(`Das Plugin hat ${modules.length} Hook-Module; übernommen wird das erste.`, `The plugin has ${modules.length} hook modules; the first one is taken over.`))
  if (manifest.dependencies?.length) report.push(t(`Abhängigkeiten (${manifest.dependencies.join(', ')}) werden nicht mitgeholt.`, `Dependencies (${manifest.dependencies.join(', ')}) are not fetched.`))

  const box = readJson(BOX)
  const upstream = manifest.name
  const existing = box.mods.find(m => (m.upstream ?? m.id) === upstream)
  if (existing && !existing.imported) throw new Error(t(`${upstream} ist schon fest in der Box`, `${upstream} is already built into the box`))
  const id = existing?.id ?? (box.mods.some(m => m.id === slug(upstream)) ? slug(upstream) + '-2' : slug(upstream))
  const target = path.join(ROOT, 'mods', id)
  const backupBox = fs.readFileSync(BOX, 'utf8')
  const backupManifest = fs.readFileSync(MANIFEST, 'utf8')
  const backupDir = existing ? target + '.alt' : null
  if (existing) fs.renameSync(target, backupDir)

  try {
    copyTree(pluginDir, target, report)
    fs.rmSync(path.join(target, 'hooks', 'hooks.json'), { force: true })
    writeJson(path.join(target, 'upstream-plugin.json'), manifest)

    const taken = new Set(box.mods.filter(m => m.id !== id).map(m => m.state?.prefix).filter(Boolean))
    const prefix = existing?.state?.prefix ?? uniquePrefix(id, taken)
    let stateRefs = 0
    for (const f of walk(target)) {
      if (!CODE_EXT.test(f) || f.endsWith('.d.ts')) continue
      const prefixes = Object.fromEntries(box.mods.filter(m => m.state?.prefix && m.id !== id).map(m => [m.upstream ?? m.state.from ?? m.id, m.state.prefix]))
      const r = rewrite(fs.readFileSync(f, 'utf8'), { upstream, prefix, id, plugin: box.plugin, prefixes })
      fs.writeFileSync(f, r.code)
      stateRefs += r.stateRefs
      for (const n of r.notes) report.push(`${path.relative(target, f)}: ${n}`)
    }

    // Contract: the original as contract.d.ts; build generates index.d.ts.
    let state = null
    if (manifest.types) {
      const src = path.join(pluginDir, manifest.types)
      const contract = path.join(target, 'types', 'contract.d.ts')
      write(contract, fs.readFileSync(src, 'utf8'))
      if (path.resolve(path.join(target, manifest.types)) !== contract) fs.rmSync(path.join(target, manifest.types), { force: true })
      state = { from: upstream, prefix, contract: rel(ROOT, contract).replace(/^\.\//, '') }
    } else if (stateRefs) {
      report.push(t('Der Mod benutzt $.state, hat aber keinen Vertrag ("types"); die Typprüfung kann scheitern.', 'The mod uses $.state but has no contract ("types"); the type check may fail.'))
    }

    const toggle = existing?.toggle ?? camel(id)
    const options = Object.entries(manifest.userConfig ?? {}).map(([field, f]) => ({
      key: toggle + pascal(field),
      field,
      ...f,
      title: `${manifest.displayName ?? pascal(upstream)}: ${f.title ?? field}`,
    }))
    if (options.some(o => o.sensitive)) report.push(t('Eine Option ist als geheim markiert; geheime Werte gehören nicht ins Fenster, sondern in /config.', 'An option is marked secret; secret values belong in /config, not in the window.'))

    const entry = {
      id,
      toggle,
      title: manifest.displayName ?? upstream,
      group: 'imported',
      description: manifest.description ?? '',
      default: existing?.default ?? false,
      entry: rel(ROOT, path.join(target, 'hooks', modules[0])).replace(/^\.\//, ''),
      imported: true,
      upstream,
      ...(options.length ? { options } : {}),
      ...(state ? { state } : {}),
      source: { url: a.url[0] ?? null, dir: pluginDir, license: manifest.license ?? null, version: manifest.version ?? null },
    }
    if (existing) box.mods[box.mods.indexOf(existing)] = entry
    else box.mods.push(entry)
    writeJson(BOX, box)

    // Report duplicate commands or tools.
    for (const d of duplicates()) report.push(d)

    build()
    const v = validate()
    if (!v.ok) throw new Error(t('Prüfung fehlgeschlagen, nichts geändert:\n', 'validation failed, nothing changed:\n') + errorsOf(v.text))
    // Record the baseline for later update checks.
    try {
      writeSnapshot({ dir: `mods/${id}`, pluginDir, url: a.url[0] ?? '', sub: a.url[0] ? parseLink(a.url[0]).sub : '', name: upstream, prefix, typesPath: manifest.types ?? null })
    } catch (err) {
      report.push(t(`Kein Grundstand für Updates: ${String(err.message ?? err)}`, `No baseline for updates: ${String(err.message ?? err)}`))
    }
    if (backupDir) fs.rmSync(backupDir, { recursive: true, force: true })
    return { ok: true, id, toggle, prefix, notes: report, validated: v.binary ?? null }
  } catch (err) {
    fs.rmSync(target, { recursive: true, force: true })
    if (backupDir) fs.renameSync(backupDir, target)
    fs.writeFileSync(BOX, backupBox)
    fs.writeFileSync(MANIFEST, backupManifest)
    try {
      build()
    } catch {
      // the old state was built; nothing to do
    }
    return { ok: false, error: String(err.message ?? err), notes: report }
  }
}

function duplicates() {
  const seen = { command: new Map(), tool: new Map() }
  const notes = []
  for (const mod of readJson(BOX).mods) {
    const dir = path.join(ROOT, 'mods', mod.id)
    if (!fs.existsSync(dir)) continue
    for (const f of walk(dir)) {
      if (!CODE_EXT.test(f) || f.endsWith('.d.ts')) continue
      const code = fs.readFileSync(f, 'utf8')
      for (const [kind, re] of [['command', /\$\.command\.register\(\{\s*name:\s*['"]([\w:-]+)['"]/g], ['tool', /\$\.tool\.register\(\{\s*name:\s*['"]([\w-]+)['"]/g]]) {
        for (const m of code.matchAll(re)) {
          const other = seen[kind].get(m[1])
          if (other && other !== mod.id) notes.push(t(`${kind === 'command' ? 'Befehl /' : 'Tool '}${m[1]} gibt es in ${other} und ${mod.id}; der zuletzt registrierte gewinnt.`, `${kind === 'command' ? 'command /' : 'tool '}${m[1]} exists in ${other} and ${mod.id}; the one registered last wins.`))
          seen[kind].set(m[1], mod.id)
        }
      }
    }
  }
  return notes
}

// Find the newest Claude Code (the desktop app often ships a newer one than PATH).
function findClaude() {
  const found = []
  const appdata = process.env.APPDATA
  if (appdata) {
    const base = path.join(appdata, 'Claude', 'claude-code')
    if (fs.existsSync(base)) {
      for (const v of fs.readdirSync(base)) {
        const vd = path.join(base, v)
        if (!fs.statSync(vd).isDirectory()) continue
        for (const h of fs.readdirSync(vd)) {
          const exe = path.join(vd, h, process.platform === 'win32' ? 'claude.exe' : 'claude')
          if (fs.existsSync(exe)) found.push({ version: v, exe })
        }
      }
    }
  }
  for (const exe of [path.join(os.homedir(), '.local', 'bin', process.platform === 'win32' ? 'claude.exe' : 'claude'), 'claude']) {
    try {
      const out = execFileSync(exe, ['--version'], { encoding: 'utf8', timeout: 20_000, stdio: ['ignore', 'pipe', 'ignore'] })
      const v = /(\d+\.\d+\.\d+)/.exec(out)?.[1]
      if (v) found.push({ version: v, exe })
    } catch {
      // not present
    }
  }
  const num = v => v.split('.').map(Number).reduce((a, b) => a * 10000 + b, 0)
  found.sort((x, y) => num(y.version) - num(x.version))
  return found[0] ?? null
}

function validate() {
  const c = findClaude()
  if (!c) return { ok: true, text: t('kein Claude Code zum Prüfen gefunden', 'no Claude Code found to validate with'), binary: null }
  try {
    const text = execFileSync(c.exe, ['plugin', 'validate', ROOT], { encoding: 'utf8', timeout: 180_000, stdio: ['ignore', 'pipe', 'pipe'] })
    return { ok: !/✘/.test(text), text, binary: `${c.exe} (${c.version})` }
  } catch (err) {
    return { ok: false, text: String(err.stdout ?? '') + String(err.stderr ?? err.message), binary: `${c.exe} (${c.version})` }
  }
}

// ---------------------------------------------------------------- Upstream updates
//
// Every mod that comes from an upstream repo has mods/<dir>/upstream.json: where it comes from
// (url, path, name, prefix), which commit our copy is based on, and the content of the
// upstream files at that commit (as JSON, so no foreign code sits in the plugin).
// An update is a three-way merge per file (git merge-file): baseline, new upstream,
// our version. The box rewrites (rewrite) are applied to both upstream versions first
// so they don't count as differences; our own changes are kept.

const UPSTREAM_FILE = 'upstream.json'

function eolOf(s) {
  return s.includes('\r\n') ? '\r\n' : '\n'
}
const lf = s => s.replace(/\r\n/g, '\n')

// Upstream path -> path in the box. The contract file is types/contract.d.ts here.
export function localPath(rel, typesPath) {
  const r = rel.split(path.sep).join('/')
  if (typesPath && r === typesPath.replace(/^\.\//, '')) return 'types/contract.d.ts'
  return r
}

function upstreamFiles(pluginDir) {
  const out = {}
  const walkUp = (dir, base) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name)
      const rel = path.relative(base, p).split(path.sep).join('/')
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name) || e.name === '.claude-plugin' || ['skills', 'agents', 'commands'].includes(e.name)) continue
        walkUp(p, base)
      } else if (e.isFile() && fs.statSync(p).size <= 2 * 1024 * 1024 && !/\.(png|jpe?g|gif|webp|mp4|woff2?|ico)$/i.test(e.name)) {
        if (rel === 'hooks/hooks.json') continue
        out[rel] = fs.readFileSync(p, 'utf8')
      }
    }
  }
  walkUp(pluginDir, pluginDir)
  return out
}

function repoRoot(dir) {
  return git(['rev-parse', '--show-toplevel'], dir).trim()
}

function headOf(dir) {
  return git(['rev-parse', 'HEAD'], dir).trim()
}

function readUpstream(dir) {
  const p = path.join(ROOT, dir, UPSTREAM_FILE)
  return fs.existsSync(p) ? readJson(p) : null
}

// Records the baseline: only the upstream files that exist in our copy.
function writeSnapshot({ dir, pluginDir, url, sub, name, prefix, typesPath }) {
  const target = path.join(ROOT, dir)
  const all = upstreamFiles(pluginDir)
  const files = {}
  for (const [rel, text] of Object.entries(all)) {
    if (fs.existsSync(path.join(target, localPath(rel, typesPath)))) files[rel] = text
  }
  // URL and subpath from the upstream's Git repo where they weren't given.
  const root = repoRoot(pluginDir)
  const realSub = path.relative(root, pluginDir).split(path.sep).join('/')
  let link = url
  if (!link) {
    try {
      link = git(['remote', 'get-url', 'origin'], root).trim()
    } catch {
      link = ''
    }
  }
  if (!link) throw new Error(t('Das Original liegt in keinem Git-Repo mit Adresse; Updates lassen sich nicht prüfen.', 'The original is in no git repo with a remote; updates cannot be checked.'))
  const snap = { url: parseLink(link).clone, path: realSub || sub || '', name, prefix: prefix ?? null, typesPath: typesPath ?? null, commit: headOf(pluginDir), at: new Date().toISOString(), files }
  writeJson(path.join(target, UPSTREAM_FILE), snap)
  return snap
}

function snapshotCmd(a) {
  const dir = String(a._[1] ?? '')
  if (!dir || !a.dir) throw new Error('snapshot <mods/...> --dir <original-plugin-ordner> --url <link> [--path p] --name <name> [--prefix p] [--types t]')
  const snap = writeSnapshot({ dir, pluginDir: path.resolve(String(a.dir)), url: String(a.url[0] ?? ''), sub: a.path ? String(a.path) : '', name: String(a.name), prefix: a.prefix ? String(a.prefix) : null, typesPath: a.types ? String(a.types) : null })
  return { ok: true, dir, commit: snap.commit, files: Object.keys(snap.files).length }
}

function vendoredDirs() {
  const base = path.join(ROOT, 'mods')
  return fs.readdirSync(base).filter(d => fs.existsSync(path.join(base, d, UPSTREAM_FILE))).map(d => `mods/${d}`)
}

// Fetches a mod's current upstream (git pull in the cache).
function fetchUpstream(snap, refresh) {
  return fetchParsed({ clone: parseLink(snap.url).clone, ref: null, sub: (snap.path ?? '').replace(/^\.?\/|\/$/g, '') }, refresh)
}

function compare(dir, refresh) {
  const snap = readUpstream(dir)
  const pluginDir = fetchUpstream(snap, refresh)
  const head = headOf(pluginDir)
  const theirs = upstreamFiles(pluginDir)
  const changed = []
  const added = []
  const removed = []
  for (const [rel, text] of Object.entries(snap.files)) {
    if (!(rel in theirs)) removed.push(rel)
    else if (lf(theirs[rel]) !== lf(text)) changed.push(rel)
  }
  for (const rel of Object.keys(theirs)) {
    if (!(rel in snap.files) && rel.startsWith('hooks/')) added.push(rel)
  }
  return { snap, pluginDir, head, theirs, changed, added, removed }
}

function updatesCmd(a) {
  const out = []
  for (const dir of vendoredDirs()) {
    try {
      const c = compare(dir, a.refresh !== false)
      const n = c.changed.length + c.added.length + c.removed.length
      out.push({
        dir,
        id: path.basename(dir),
        name: c.snap.name,
        url: c.snap.url,
        from: c.snap.commit.slice(0, 7),
        to: c.head.slice(0, 7),
        status: n === 0 ? 'current' : 'update',
        changed: c.changed,
        added: c.added,
        removed: c.removed,
      })
    } catch (err) {
      out.push({ dir, id: path.basename(dir), status: 'error', error: String(err.message ?? err).split('\n')[0] })
    }
  }
  return { ok: true, mods: out }
}

function rewriteFor(snap, dir, rel, text) {
  if (!CODE_EXT.test(rel) || rel.endsWith('.d.ts')) return text
  const box = readJson(BOX)
  const id = path.basename(dir)
  const prefixes = Object.fromEntries(box.mods.filter(m => m.state?.prefix).map(m => [m.upstream ?? m.state.from ?? m.id, m.state.prefix]))
  return rewrite(text, { upstream: snap.name, prefix: snap.prefix ?? 'x', id, plugin: box.plugin, prefixes }).code
}

function diffCmd(a) {
  const dir = resolveDir(String(a._[1] ?? ''))
  const c = compare(dir, false)
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mod-box-diff-'))
  const parts = []
  try {
    for (const rel of [...c.changed, ...c.added, ...c.removed]) {
      const A = path.join(tmp, 'a.txt')
      const B = path.join(tmp, 'b.txt')
      fs.writeFileSync(A, lf(c.snap.files[rel] ?? ''))
      fs.writeFileSync(B, lf(c.theirs[rel] ?? ''))
      let out = ''
      try {
        out = execFileSync('git', ['-c', 'core.autocrlf=false', 'diff', '--no-index', '--no-color', '-U3', A, B], { encoding: 'utf8' })
      } catch (err) {
        out = String(err.stdout ?? '') // exit 1 = differences
      }
      parts.push(out.replace(/^diff --git .*\n/m, '').replace(/^--- .*$/m, `--- a/${rel}`).replace(/^\+\+\+ .*$/m, `+++ b/${rel}`))
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true })
  }
  return { ok: true, dir, from: c.snap.commit.slice(0, 7), to: c.head.slice(0, 7), diff: parts.join('\n').slice(0, 200_000) }
}

function resolveDir(idOrDir) {
  if (!idOrDir) throw new Error(t('Mod angeben', 'name a mod'))
  const dir = idOrDir.startsWith('mods/') ? idOrDir : `mods/${idOrDir}`
  if (!readUpstream(dir)) throw new Error(t(`${dir} hat keinen Grundstand (upstream.json)`, `${dir} has no baseline (upstream.json)`))
  return dir
}

export function mergeText(ours, base, theirs) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mod-box-merge-'))
  try {
    const O = path.join(tmp, 'ours')
    const B = path.join(tmp, 'base')
    const T = path.join(tmp, 'theirs')
    fs.writeFileSync(O, lf(ours))
    fs.writeFileSync(B, lf(base))
    fs.writeFileSync(T, lf(theirs))
    try {
      const merged = execFileSync('git', ['-c', 'core.autocrlf=false', 'merge-file', '-p', '-L', 'mod-box', '-L', 'base', '-L', 'original', O, B, T], { encoding: 'utf8' })
      return { text: merged, conflicts: 0 }
    } catch (err) {
      // Exit code > 0: that many conflicts; stdout holds the result with markers.
      if (typeof err.status === 'number' && err.status > 0 && err.stdout) return { text: String(err.stdout), conflicts: err.status }
      throw err
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true })
  }
}

function updateCmd(a) {
  const dir = resolveDir(String(a._[1] ?? ''))
  const c = compare(dir, a.refresh === true)
  if (c.changed.length + c.added.length + c.removed.length === 0) {
    return { ok: true, dir, from: c.snap.commit.slice(0, 7), to: c.head.slice(0, 7), files: 0, notes: [t('Schon aktuell, nichts zu tun.', 'Already current, nothing to do.')] }
  }
  const target = path.join(ROOT, dir)
  const typesPath = c.snap.typesPath
  const writes = []
  const deletes = []
  const conflicts = []
  const notes = []
  for (const rel of c.changed) {
    const local = path.join(target, localPath(rel, typesPath))
    if (!fs.existsSync(local)) continue
    const ours = fs.readFileSync(local, 'utf8')
    const base = rewriteFor(c.snap, dir, rel, c.snap.files[rel])
    const theirs = rewriteFor(c.snap, dir, rel, c.theirs[rel])
    const m = mergeText(ours, base, theirs)
    if (m.conflicts) conflicts.push(`${localPath(rel, typesPath)} (${m.conflicts})`)
    else writes.push([local, m.text.split('\n').join(eolOf(ours))])
  }
  for (const rel of c.added) {
    writes.push([path.join(target, localPath(rel, typesPath)), rewriteFor(c.snap, dir, rel, c.theirs[rel])])
    notes.push(t(`neu: ${rel}`, `new: ${rel}`))
  }
  for (const rel of c.removed) {
    const local = path.join(target, localPath(rel, typesPath))
    if (!fs.existsSync(local)) continue
    if (lf(fs.readFileSync(local, 'utf8')) === lf(rewriteFor(c.snap, dir, rel, c.snap.files[rel]))) deletes.push(local)
    else notes.push(t(`${rel} gibt es im Original nicht mehr; unsere geänderte Fassung bleibt.`, `${rel} is gone upstream; our changed version stays.`))
  }
  if (conflicts.length) {
    return { ok: false, dir, error: t(`Konflikte, nichts geändert: ${conflicts.join(', ')}. Unsere Anpassungen und das Original ändern dieselben Stellen; das braucht eine Entscheidung von Hand.`, `Conflicts, nothing changed: ${conflicts.join(', ')}. Our changes and the original touch the same lines; this needs a decision by hand.`), notes }
  }
  // Back up, write, update the baseline, build, check; roll back on error.
  const backup = new Map()
  for (const [p] of writes) backup.set(p, fs.existsSync(p) ? fs.readFileSync(p) : null)
  for (const p of deletes) backup.set(p, fs.readFileSync(p))
  const snapPath = path.join(target, UPSTREAM_FILE)
  const snapBackup = fs.readFileSync(snapPath)
  try {
    for (const [p, text] of writes) write(p, text)
    for (const p of deletes) fs.rmSync(p, { force: true })
    writeSnapshot({ dir, pluginDir: c.pluginDir, url: c.snap.url, sub: c.snap.path, name: c.snap.name, prefix: c.snap.prefix, typesPath })
    build()
    const v = validate()
    if (!v.ok) throw new Error(t('Prüfung fehlgeschlagen, zurückgerollt:\n', 'validation failed, rolled back:\n') + errorsOf(v.text))
    return { ok: true, dir, from: c.snap.commit.slice(0, 7), to: c.head.slice(0, 7), files: writes.length + deletes.length, notes }
  } catch (err) {
    for (const [p, content] of backup) {
      if (content === null) fs.rmSync(p, { force: true })
      else fs.writeFileSync(p, content)
    }
    fs.writeFileSync(snapPath, snapBackup)
    try {
      build()
    } catch {
      // the old state was built
    }
    return { ok: false, dir, error: String(err.message ?? err), notes }
  }
}

// Claude Code (especially the desktop app) loads the box from a copy under
// ~/.claude/plugins/cache/<marketplace>/<plugin>/<version>, created at install time.
// For changes to arrive: bump the version, build, check, `claude plugin update`.
function releaseCmd() {
  // The box is loaded straight from this folder (CLAUDE_CODE_PLUGIN_DIRS); a running session reloads
  // it by itself. A marketplace install would run a copy instead and lose the /config rows.
  build()
  const v = validate()
  if (!v.ok) throw new Error(t('Prüfung fehlgeschlagen:\n', 'validation failed:\n') + errorsOf(v.text))
  const manifest = readJson(MANIFEST)
  const parts = String(manifest.version ?? '0.1.0').split('.').map(n => Number(n) || 0)
  while (parts.length < 3) parts.push(0)
  parts[2] += 1
  manifest.version = parts.join('.')
  writeJson(MANIFEST, manifest)
  return { ok: true, version: manifest.version, note: t('Geladen wird direkt aus diesem Ordner; laufende Sitzungen laden von selbst neu (sonst Claude neu starten).', 'Loaded straight from this folder; running sessions reload by themselves (otherwise restart Claude).') }
}

// Only the errors from `claude plugin validate` output: the ❯ lines under a ✘.
export function errorsOf(text) {
  const out = []
  let inError = false
  for (const line of String(text).split('\n')) {
    if (/✘/.test(line)) inError = !/Validation failed/.test(line)
    else if (/^Validating|⚠/.test(line)) inError = false
    else if (inError && line.trim()) out.push(line.trim().replace(/^❯\s*/, '').replace(/^modules\.\.\/register\.ts:\s*/, ''))
  }
  return (out.length ? out : [String(text).trim().split('\n').pop() ?? '']).join('\n').slice(0, 1200)
}

function remove(id) {
  const box = readJson(BOX)
  const mod = box.mods.find(m => m.id === id)
  if (!mod) throw new Error(t(`${id} ist nicht in der Box`, `${id} is not in the box`))
  if (!mod.imported) throw new Error(t(`${id} gehört fest zur Box; ausschalten statt entfernen`, `${id} is built into the box; switch it off instead of removing it`))
  box.mods = box.mods.filter(m => m !== mod)
  writeJson(BOX, box)
  fs.rmSync(path.join(ROOT, 'mods', id), { recursive: true, force: true })
  build()
  return { ok: true, id }
}

// ---------------------------------------------------------------- main

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const a = args(process.argv.slice(2))
  if (a.lang === 'en') LANG = 'en'
  const cmd = a._[0]
  let result
  try {
    if (cmd === 'build') result = build()
    else if (cmd === 'catalog') result = catalog(a)
    else if (cmd === 'import') result = importMod(a)
    else if (cmd === 'remove') result = remove(a._[1])
    else if (cmd === 'validate') result = validate()
    else if (cmd === 'snapshot') result = snapshotCmd(a)
    else if (cmd === 'release') result = releaseCmd()
    else if (cmd === 'updates') result = updatesCmd(a)
    else if (cmd === 'diff') result = diffCmd(a)
    else if (cmd === 'update') result = updateCmd(a)
    else result = { ok: false, error: 'Befehle: build | catalog [--url L]... [--refresh] | import (--dir D | --url L) [--plugin N] | remove <id> | validate' }
  } catch (err) {
    result = { ok: false, error: String(err.message ?? err) }
  }
  process.stdout.write(JSON.stringify(result) + '\n')
  process.exitCode = result.ok ? 0 : 1
}
