// Copies a plugin into the box. Everything comes along (media, docs, assets): a file the code reads
// must not go missing. Left out: version control, installed packages, the manifest (the box has its
// own), and test folders (the box would run them as its own tests). A file over 5 MB that the code
// names is a loss and stops the import; one it does not name is left out with a note.
const COPY_SKIP = new Set(['.git', 'node_modules', '.claude-plugin', '.github'])
const TEST_DIRS = new Set(['tests', 'test', '__tests__'])
function copyTree(from, to, report, lost, code = null) {
  fs.mkdirSync(to, { recursive: true })
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, e.name)
    const d = path.join(to, e.name)
    if (e.isDirectory()) {
      if (COPY_SKIP.has(e.name)) continue
      if (TEST_DIRS.has(e.name)) {
        report.push(t(`Testordner ${e.name}/ nicht übernommen (die Box würde ihn als eigene Tests ausführen).`, `Test folder ${e.name}/ not taken over (the box would run it as its own tests).`))
        continue
      }
      copyTree(s, d, report, lost, code)
    } else if (e.isFile()) {
      if (/^(package-lock\.json|bun\.lockb?|yarn\.lock|pnpm-lock\.yaml)$/.test(e.name)) continue
      if (fs.statSync(s).size > 5 * 1024 * 1024) {
        if (code && code.includes(e.name)) lost.push(t(`${e.name} (größer als 5 MB, der Code benutzt sie)`, `${e.name} (larger than 5 MB, the code uses it)`))
        else report.push(t(`${e.name} nicht übernommen (größer als 5 MB, im Code nicht genannt).`, `${e.name} not taken over (larger than 5 MB, not named in the code).`))
        continue
      }
      fs.copyFileSync(s, d)
    }
  }
}

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else out.push(p)
  }
  return out
}

function uniquePrefix(id, taken) {
  const parts = id.split(/[^a-z0-9]+/i).filter(Boolean)
  let base = parts.map(p => p[0]).join('').toLowerCase()
  if (base.length < 2) base = id.replace(/[^a-z0-9]/gi, '').slice(0, 3).toLowerCase()
  let p = base
  for (let i = 2; taken.has(p); i++) p = base + i
  return p
}

// Rewrites a mod's code for the box. Returns notes.
// `prefixes` maps every plugin name living in the box to its state prefix (its own
// included), so references to other box mods' state are translated too.
export function rewrite(code, { upstream, prefix, id, plugin, prefixes = {}, storePrefix = null }) {
  const notes = []
  const q = upstream.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const map = { ...prefixes, [upstream]: prefix }
  let n = 0
  // { plugin: 'name', key: 'x' } and { key: 'x', plugin: 'name' }
  code = code.replace(/plugin:\s*(['"])([\w@/.-]+)\1(\s*,\s*key:\s*)(['"])([\w$-]+)\4/g, (all, _q, name, mid, kq, key) => {
    if (!(name in map)) return all
    if (name === upstream) n++
    return `plugin: '${plugin}'${mid}${kq}${map[name]}_${key}${kq}`
  })
  code = code.replace(/key:\s*(['"])([\w$-]+)\1(\s*,\s*plugin:\s*)(['"])([\w@/.-]+)\4/g, (all, kq, key, mid, _q, name) => {
    if (!(name in map)) return all
    if (name === upstream) n++
    return `key: ${kq}${map[name]}_${key}${kq}${mid}'${plugin}'`
  })
  if (new RegExp(`plugin:\\s*['"]${q}['"]`).test(code)) notes.push(t(`Ein State-Verweis auf "${upstream}" hat eine ungewöhnliche Form und wurde nicht umgeschrieben.`, `A state reference to "${upstream}" has an unusual form and was not rewritten.`))
  for (const m of code.matchAll(/plugin:\s*['"]([\w@/.-]+)['"]\s*,\s*key:/g)) {
    if (m[1] !== plugin && !(m[1] in map)) notes.push(t(`Liest den State des Plugins "${m[1]}", das nicht in der Box ist; dieser Teil bleibt leer, solange es nicht separat installiert ist.`, `Reads the state of plugin "${m[1]}", which is not in the box; that part stays empty unless it is installed separately.`))
  }
  // Tools are named mcp__<plugin>__<name>
  code = code.replace(new RegExp(`mcp__${q}__`, 'g'), `mcp__${plugin}__`)
  // Files from the plugin folder now live under mods/<id>/
  code = code.replace(/(\$\.plugin\.root\s*\+\s*)(['"`])\//g, `$1$2/mods/${id}/`)
  code = code.replace(/\$\{\s*\$\.plugin\.root\s*\}\//g, `\${$.plugin.root}/mods/${id}/`)
  if (/\$\.plugin\.root(?!\s*\+\s*['"`]\/mods\/)(?!\s*\}\/mods\/)/.test(code)) notes.push(t('$.plugin.root wird in einer Form benutzt, die nicht automatisch umgeschrieben wurde; Pfade prüfen.', '$.plugin.root is used in a form that was not rewritten automatically; check the paths.'))
  // Assets ($.audio.play({ asset }) and the like) are named relative to the plugin root.
  code = code.replace(/(\basset:\s*)(['"`])(?!mods\/)([^'"`$]+)\2/g, (_all, head, q, p) => `${head}${q}mods/${id}/${p.replace(/^\.?\//, '')}${q}`)
  if (/\basset:\s*(?!['"`])/.test(code)) notes.push(t('Ein Asset-Pfad ist nicht wörtlich angegeben und wurde nicht umgeschrieben; prüfen.', 'An asset path is not a literal and was not rewritten; check it.'))
  // $.store is one per plugin: in the box all mods share it, so literal keys get the mod's prefix.
  if (storePrefix) {
    code = code.replace(/(\$\.store\.(?:get|set|delete)\(\s*)(['"`])(?!\w+:)/g, `$1$2${storePrefix}:`)
    if (/\$\.store\.(?:get|set|delete)\(\s*(?!['"`])/.test(code)) notes.push(t('$.store wird mit einem berechneten Schlüssel benutzt; der kann mit anderen Mods kollidieren.', '$.store is used with a computed key; it may clash with other mods.'))
    if (/\$\.store\.keys\(/.test(code)) notes.push(t('$.store.keys() sieht in der Box auch die Schlüssel anderer Mods.', '$.store.keys() sees other mods\' keys too inside the box.'))
  }
  // Several mods may watch the same event if each has a matcher: {} matches everything.
  code = code.replace(/(?<![\w.$])on\((['"][\w.*!]+['"]),(?!\s*\{)\s*/g, 'on($1, {}, ')
  return { code, notes, stateRefs: n }
}

/**
 * Whether a profile switches a mod on. A rule is "defaults" (each mod's own default), "all", or an
 * object of attribute lists that must all match, e.g. { group: ['guards'] } or { tokens: ['none'] }.
 * The old form { all, on: [...] } still works. New mods are judged by the same rule.
 */
export function ruleSays(rule, m) {
  if (rule === 'defaults') return m.default === true
  if (rule === 'all') return true
  if (!rule || typeof rule !== 'object') return false
  if (Array.isArray(rule.on) || 'all' in rule) return rule.on?.includes(m.toggle) ? true : rule.all === true
  const value = { group: m.group ?? 'imported', tokens: m.tokens ?? (m.costs ? 'always' : 'none'), imported: m.imported === true }
  return Object.entries(rule).every(([k, list]) => (Array.isArray(list) ? list : [list]).includes(value[k]))
}

/**
 * A first guess at what kind of mod a folder holds, read from its code: group, token use,
 * commands and where it can run. Claude (or the person) checks and corrects it in box.json.
 */
export function analyze(code) {
  const has = re => re.test(code)
  const surfaceAware = has(/surface\s*[!=]==/)
  const runs = new Set([...code.matchAll(/process\.run\(\s*\[\s*['"]([\w.-]+)/g)].map(x => x[1].toLowerCase()))
  const needs = []
  if (runs.has('git')) needs.push('git')
  if (runs.has('gh')) needs.push('gh')
  if (runs.has('node') || runs.has('npm') || runs.has('npx')) needs.push('node')
  if (runs.has('bash') || runs.has('sh')) needs.push('bash')
  // PowerShell behind a Windows check is an extra for Windows, not a requirement.
  const osAware = has(/Windows_NT|isWin|platform/)
  if ((runs.has('powershell') || runs.has('pwsh')) && !osAware) needs.push('powershell')
  let surfaces = ['terminal', 'desktop', 'vscode', 'mobile']
  const drop = list => (surfaces = surfaces.filter(x => !list.includes(x)))
  if (!surfaceAware && has(/\b(Raster|Image)\b/)) surfaces = ['terminal']
  if (!surfaceAware && has(/\bSvg\b/)) drop(['terminal'])
  if (has(/\bClient\b/)) drop(['mobile', 'vscode'])
  if (has(/\b(Input|Select)\b/)) drop(['mobile'])
  const os = needs.includes('powershell') && !runs.has('sh') && !runs.has('bash') ? ['windows'] : ['windows', 'mac', 'linux']
  const tokens = has(/\$\.model\.\w+/) ? 'always' : 'none'
  const group = has(/\bdeny\b/) && has(/tool\.(call|check)/) ? 'guards'
    : tokens === 'always' && has(/turn\.complete/) ? 'watchers'
    : has(/compact|cache_read|cacheRead|context/i) && !has(/component:\s*['"]Pane['"]/) ? 'context'
    : has(/component:\s*['"](Pane|AbovePrompt)['"]/) ? 'display'
    : 'imported'
  const commands = [...new Set([...code.matchAll(/command\.register\(\s*\{[^}]*?name:\s*['"`]([\w-]+)/g)].map(x => '/' + x[1]))]
  return { group, tokens, commands, compat: { surfaces, os, needs } }
}

/** analyze <id|dir>: the guess for a mod in the box or any folder, next to what box.json says. */
function analyzeCmd(target) {
  if (!target) throw new Error(t('analyze <id|ordner>', 'analyze <id|dir>'))
  const box = readJson(BOX)
  const m = box.mods.find(x => x.id === target || x.toggle === target)
  const dir = m ? path.join(ROOT, 'mods', m.id) : path.resolve(target)
  const code = walk(dir).filter(f => CODE_EXT.test(f) && !f.endsWith('.d.ts')).map(f => fs.readFileSync(f, 'utf8')).join('\n')
  return { ok: true, guess: analyze(code), current: m ? { group: m.group, tokens: m.tokens ?? null, compat: m.compat ?? null, commands: (m.commands ?? []).map(c => c.name) } : null }
}

