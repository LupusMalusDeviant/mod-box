#!/usr/bin/env node
// Mod Box tool. Runs on Node (no dependencies) and prints JSON to stdout.
//
//   node tools/box.mjs build
//       Generates from box.json: hooks/register.ts (dispatcher), types/index.d.ts (state contract),
//       the userConfig in .claude-plugin/plugin.json, mods/<id>/types/index.d.ts (re-exports)
//       and mods/settings/hooks/catalog.ts (what the window shows).
//   node tools/box.mjs catalog [--url <git-link>]... [--refresh]
//       Lists the connected Claude marketplaces and your own Git links with their plugins.
//   node tools/box.mjs import --dir <repo-or-marketplace-folder> [--plugin <name>]
//   node tools/box.mjs import --url <git-link> [--plugin <name>]
//       Fetches the mod, rewrites it for the box, adds it to box.json, builds and checks.
//       If the check fails, everything is rolled back.
//   node tools/box.mjs remove <id>
//       Removes an imported mod again.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const BOX = path.join(ROOT, 'box.json')
const MANIFEST = path.join(ROOT, '.claude-plugin', 'plugin.json')
const CACHE = path.join(os.homedir(), '.claude', 'mod-box', 'sources')
const CODE_EXT = /\.(tsx?|jsx?|mjs|cjs|mts|cts)$/
const SKIP_DIRS = new Set(['.git', 'node_modules', 'tests', 'test', '__tests__', 'screenshots', 'media', 'images', 'site', 'docs', '.github', 'dist'])
// Message language (--lang de|en); the window passes its setting on.
let LANG = 'de'
const t = (de, en) => (LANG === 'en' ? en : de)

const GENERATED = '// GENERATED by tools/box.mjs build. Do not edit by hand: edit box.json and rebuild.\n'

// ---------------------------------------------------------------- Helpers

const readJson = p => JSON.parse(fs.readFileSync(p, 'utf8').replace(/^﻿/, ''))
const writeJson = (p, v) => fs.writeFileSync(p, JSON.stringify(v, null, 2) + '\n')
const write = (p, text) => {
  fs.mkdirSync(path.dirname(p), { recursive: true })
  fs.writeFileSync(p, text)
}
const rel = (from, to) => {
  const r = path.relative(from, to).split(path.sep).join('/')
  return r.startsWith('.') ? r : './' + r
}
const pascal = s => s.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(w => w[0].toUpperCase() + w.slice(1)).join('')
const camel = s => {
  const p = pascal(s)
  return p ? p[0].toLowerCase() + p.slice(1) : s
}
const slug = s => s.toLowerCase().replace(/^https?:\/\//, '').replace(/\.git$/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 80)

function args(argv) {
  const out = { _: [], url: [] }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--url') out.url.push(argv[++i])
    else if (a.startsWith('--')) {
      const k = a.slice(2)
      const v = argv[i + 1]
      if (v === undefined || v.startsWith('--')) out[k] = true
      else out[k] = argv[++i]
    } else out._.push(a)
  }
  return out
}

// Matching bracket for `open` (index of a "{"), roughly skipping strings and comments.
function matchBrace(text, open) {
  let depth = 0
  for (let i = open; i < text.length; i++) {
    const c = text[i]
    if (c === '/' && text[i + 1] === '/') { i = text.indexOf('\n', i); if (i < 0) return -1; continue }
    if (c === '/' && text[i + 1] === '*') { i = text.indexOf('*/', i + 2) + 1; if (i <= 0) return -1; continue }
    if (c === '"' || c === "'" || c === '`') {
      for (i++; i < text.length && text[i] !== c; i++) if (text[i] === '\\') i++
      continue
    }
    if (c === '{') depth++
    else if (c === '}' && --depth === 0) return i
  }
  return -1
}

// ---------------------------------------------------------------- build

function contractOf(mod, used) {
  const file = path.join(ROOT, mod.state.contract)
  let text = fs.readFileSync(file, 'utf8')
  if (/^[ \t]*(?:import[\s{*'"]|export[^;\n]*\sfrom\s|\/\/\/[ \t]*<reference)/m.test(text)) {
    throw new Error(t(`${mod.state.contract}: der Vertrag muss ohne import/reference auskommen`, `${mod.state.contract}: the contract must not use import/reference`))
  }
  let members = ''
  const m = /declare\s+module\s+['"]claude-code['"]\s*\{/.exec(text)
  if (m) {
    const end = matchBrace(text, m.index + m[0].length - 1)
    const block = text.slice(m.index, end + 1)
    text = text.slice(0, m.index) + text.slice(end + 1)
    const from = mod.state.from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const e = new RegExp(`(['"]?)${from}\\1\\s*\\??:\\s*\\{`).exec(block)
    if (e) members = block.slice(e.index + e[0].length, matchBrace(block, e.index + e[0].length - 1))
  }
  // Rename top-level names if an earlier mod already uses them.
  const names = [...text.matchAll(/^(?:export\s+)?(?:declare\s+)?(?:type|interface|enum|const\s+enum|class)\s+(\w+)/gm)].map(x => x[1])
  const exported = new Set([...text.matchAll(/^export\s+(?:declare\s+)?(?:type|interface|enum|const\s+enum|class)\s+(\w+)/gm)].map(x => x[1]))
  const renames = {}
  for (const n of names) {
    let next = n
    if (used.has(next)) next = pascal(mod.id) + n
    while (used.has(next)) next = '_' + next
    used.add(next)
    if (next !== n) renames[n] = next
  }
  const rename = s => {
    for (const [a, b] of Object.entries(renames)) s = s.replace(new RegExp(`(?<![\\w.$'"])${a}(?![\\w'"$])`, 'g'), b)
    return s
  }
  text = rename(text)
  members = rename(members)
  const reexports = [...exported].map(n => (renames[n] ? `${renames[n]} as ${n}` : n))
  return { text: text.trim(), members: prefixMembers(members, mod.state.prefix).replace(/^\n+|\s+$/g, ''), reexports }
}

// Prefixes every top-level key of a member list with "<prefix>_",
// whether there is one member per line or several separated by ; or ,.
export function prefixMembers(members, prefix) {
  let out = ''
  let depth = 0
  let atStart = true
  for (let i = 0; i < members.length; i++) {
    const c = members[i]
    if (c === '/' && members[i + 1] === '/') {
      const end = members.indexOf('\n', i)
      const stop = end < 0 ? members.length : end
      out += members.slice(i, stop)
      i = stop - 1
      continue
    }
    if (c === '/' && members[i + 1] === '*') {
      const end = members.indexOf('*/', i + 2)
      const stop = end < 0 ? members.length : end + 2
      out += members.slice(i, stop)
      i = stop - 1
      continue
    }
    if (c === '"' || c === "'" || c === '`') {
      if (depth === 0 && atStart) {
        const m = /^(['"])([A-Za-z_$][\w$-]*)\1(\??)\s*:/.exec(members.slice(i))
        if (m) {
          out += `${prefix}_${m[2]}${m[3]}:`
          i += m[0].length - 1
          atStart = false
          continue
        }
      }
      let j = i + 1
      while (j < members.length && members[j] !== c) j += members[j] === '\\' ? 2 : 1
      out += members.slice(i, j + 1)
      i = j
      continue
    }
    if (depth === 0 && atStart && /[A-Za-z_$]/.test(c)) {
      const m = /^(readonly\s+)?([A-Za-z_$][\w$]*)(\??)\s*:/.exec(members.slice(i))
      if (m) {
        out += `${m[1] ?? ''}${prefix}_${m[2]}${m[3]}:`
        i += m[0].length - 1
        atStart = false
        continue
      }
      atStart = false
    }
    if ('{([<'.includes(c)) depth++
    else if ('})]>'.includes(c) && !(c === '>' && members[i - 1] === '=')) depth--
    if (depth === 0 && (c === ';' || c === ',' || c === '\n')) atStart = true
    else if (!/\s/.test(c)) atStart = false
    out += c
  }
  return out
}

function build() {
  const box = readJson(BOX)
  const mods = box.mods
  // Mods with "band": true draw through the band manager; each gets the option
  // <toggle>Show (band | status | off), read only by the window (field "__show" is not passed on).
  for (const mod of mods) {
    if (!mod.band || mod.core) continue
    const key = mod.toggle + 'Show'
    mod.options = (mod.options ?? []).filter(o => o.key !== key)
    mod.options.push({
      key,
      field: '__show',
      type: 'string',
      default: 'band',
      options: ['band', 'status', 'off'],
      title: `${mod.title}: display`,
      title_de: `${mod.title_de ?? mod.title}: Anzeige`,
      description: 'band: above the prompt. status: in the status line. off: not shown (the mod keeps working).',
      description_de: 'Band: über dem Prompt. Statuszeile: in der Statuszeile. aus: nicht angezeigt (der Mod arbeitet weiter).',
      labels: { de: { band: 'Band', status: 'Statuszeile', off: 'aus' }, en: { band: 'band', status: 'status line', off: 'off' } },
    })
  }
  // Defaults of all settings and options: "pass" may point to either.
  const settingDefault = Object.fromEntries([...(box.settings ?? []), ...mods.flatMap(m => m.options ?? [])].map(s => [s.key, s.default]))

  // 1. Contract
  const used = new Set()
  const parts = []
  const members = []
  for (const mod of mods) {
    if (!mod.state) continue
    const c = contractOf(mod, used)
    parts.push(`// ---- ${mod.id} ----\n\n${c.text}\n`)
    if (c.members) members.push(`      // ${mod.id}\n` + c.members.trim().split('\n').map(l => '      ' + l.trim()).join('\n'))
    const typesDir = path.join(ROOT, 'mods', mod.id, 'types')
    write(
      path.join(typesDir, 'index.d.ts'),
      GENERATED + (c.reexports.length ? `export type { ${c.reexports.join(', ')} } from '${rel(typesDir, path.join(ROOT, 'types'))}'\n` : 'export {}\n'),
    )
  }
  write(
    path.join(ROOT, 'types', 'index.d.ts'),
    GENERATED +
      `// Mod Box contract: the $.state values of all sub-mods under "${box.plugin}", each with its mod prefix.\n\n` +
      parts.join('\n') +
      `\ndeclare module 'claude-code' {\n  interface PluginState {\n    '${box.plugin}': {\n${members.join('\n\n')}\n    }\n  }\n}\n`,
  )

  // 2. Dispatcher
  const imports = []
  const calls = []
  mods.forEach((mod, i) => {
    const spec = rel(path.join(ROOT, 'hooks'), path.join(ROOT, mod.entry)).replace(/\.(tsx?|mts|cts)$/, '')
    imports.push(`import { register as m${i} } from '${spec}' // ${mod.id}`)
    const opts = []
    for (const o of mod.options ?? []) if (!o.field.startsWith('__')) opts.push(`${JSON.stringify(o.field)}: opt(o, ${JSON.stringify(o.key)}, ${JSON.stringify(o.default ?? '')})`)
    for (const [field, key] of Object.entries(mod.pass ?? {})) opts.push(`${JSON.stringify(field)}: opt(o, ${JSON.stringify(key)}, ${JSON.stringify(settingDefault[key] ?? '')})`)
    // The core (window, band manager) gets all options: it reads switches, display and order.
    if (mod.core) calls.push(`  ;(m${i} as any)(on, o) // ${mod.id}`)
    else calls.push(`  if (isOn(o, ${JSON.stringify(mod.toggle)}, ${mod.default === true})) (m${i} as any)(on, { ${opts.join(', ')} })`)
  })
  write(
    path.join(ROOT, 'hooks', 'register.ts'),
    GENERATED +
      `// Dispatcher: registers each sub-mod only if its switch is on. Toggling one reloads.\n` +
      `import type { Register } from 'claude-code'\n\n${imports.join('\n')}\n\n` +
      `export function isOn(options: Record<string, unknown>, key: string, fallback: boolean): boolean {\n` +
      `  const v = options[key]\n  return typeof v === 'boolean' ? v : v === 'true' ? true : v === 'false' ? false : fallback\n}\n\n` +
      `export function opt(options: Record<string, unknown>, key: string, fallback: string): string {\n` +
      `  const v = options[key]\n  return typeof v === 'string' && v !== '' ? v : typeof v === 'number' || typeof v === 'boolean' ? String(v) : fallback\n}\n\n` +
      `export const register: Register = (on, options) => {\n  const o = (options ?? {}) as Record<string, unknown>\n${calls.join('\n')}\n}\n`,
  )

  // 3. Manifest
  const manifest = readJson(MANIFEST)
  const userConfig = {}
  for (const s of box.settings ?? []) userConfig[s.key] = strip(s)
  for (const mod of mods) {
    if (mod.core) continue
    userConfig[mod.toggle] = {
      type: 'boolean',
      title: mod.title,
      description: (mod.description ?? '') + (mod.costs ? ` Costs tokens: ${mod.costs}.` : ''),
      default: mod.default === true,
    }
  }
  for (const mod of mods) for (const o of mod.options ?? []) userConfig[o.key] = strip(o)
  manifest.userConfig = userConfig
  manifest.description = `${mods.filter(m => !m.core).length} Claude Code mods in one plugin, each switchable on its own; /mod-box opens the window to switch, configure and import mods.`
  writeJson(MANIFEST, manifest)

  // 4. Catalog for the window
  const toggles = mods.filter(m => !m.core)
  const profiles = Object.entries(box.profiles ?? {}).map(([id, p]) => ({
    id,
    label: { en: p.en ?? id, de: p.de ?? p.en ?? id },
    set: toggles.map(m => [m.toggle, p.set === 'defaults' ? m.default === true : p.set?.on?.includes(m.toggle) ? true : p.set?.all === true]),
  }))
  const field = o => ({ key: o.key, title: both(o, 'title'), description: both(o, 'description'), labels: o.labels ?? {}, options: Array.isArray(o.options) ? o.options.map(String) : null, default: o.default ?? '' })
  const katalog = toggles.map(m => ({
    id: m.id,
    toggle: m.toggle,
    default: m.default === true,
    band: m.band === true,
    title: both(m, 'title'),
    description: both(m, 'description'),
    group: m.group ?? 'imported',
    costs: m.costs ? both(m, 'costs') : null,
    params: (m.options ?? []).map(field),
    imported: m.imported === true,
    upstream: m.upstream ?? m.id,
    source: m.source?.url ?? null,
    commands: (m.commands ?? []).map(c => ({ name: c.name, text: { en: c.en ?? c.name, de: c.de ?? c.en ?? c.name } })),
  }))
  const groups = { imported: { en: 'Imported', de: 'Übernommen' }, ...(box.groups ?? {}) }
  write(
    path.join(ROOT, 'mods', 'settings', 'hooks', 'catalog.ts'),
    GENERATED +
      `export type Text = { en: string; de: string }\n` +
      `export type CatalogField = { key: string; title: Text; description: Text; labels: Record<string, Record<string, string>>; options: string[] | null; default: string | boolean }\n` +
      `export type CatalogMod = { id: string; toggle: string; default: boolean; band: boolean; title: Text; description: Text; group: string; costs: Text | null; params: CatalogField[]; imported: boolean; upstream: string; source: string | null; commands: Array<{ name: string; text: Text }> }\n` +
      `export type CatalogProfile = { id: string; label: Text; set: Array<[string, boolean]> }\n\n` +
      `export const PLUGIN = ${JSON.stringify(box.plugin)}\n` +
      `export const SETTINGS: CatalogField[] = ${JSON.stringify((box.settings ?? []).map(field), null, 2)}\n` +
      `export const GROUPS: Record<string, Text> = ${JSON.stringify(groups, null, 2)}\n` +
      `export const CATALOG: CatalogMod[] = ${JSON.stringify(katalog, null, 2)}\n` +
      `export const PROFILES: CatalogProfile[] = ${JSON.stringify(profiles, null, 2)}\n`,
  )

  // 4b. Which events each mod subscribes to (for diagnosis: who may be behind an error).
  const hooks = {}
  for (const mod of mods) {
    const dirs = [path.join(ROOT, path.dirname(mod.entry)), ...(mod.extraDirs ?? []).map(d => path.join(ROOT, d))]
    const events = new Set()
    for (const f of dirs.flatMap(dir => (fs.existsSync(dir) ? walk(dir) : []))) {
      if (!CODE_EXT.test(f) || f.endsWith('.d.ts')) continue
      for (const m of fs.readFileSync(f, 'utf8').matchAll(/(?<![\w.$])on\(\s*(['"])([\w.*!:-]+)\1/g)) events.add(m[2])
    }
    hooks[mod.core ? mod.id : mod.toggle] = [...events].sort()
  }
  write(
    path.join(ROOT, 'mods', 'settings', 'hooks', 'hooks-table.ts'),
    GENERATED + `/** The events each mod hooks (switch key, or the id of a core mod). */\nexport const HOOKS: Record<string, string[]> = ${JSON.stringify(hooks, null, 2)}\n`,
  )

  // 5. Band manager: which mods hand their display to it (the window sets the order).
  const bandMods = toggles.filter(m => m.band)
  write(
    path.join(ROOT, 'mods', 'settings', 'hooks', 'bands.ts'),
    GENERATED + `export const BAND_IDS: string[] = ${JSON.stringify(bandMods.map(m => m.toggle))}\n`,
  )
  return { ok: true, mods: mods.length }
}

// Only the fields userConfig knows; translations and display names stay in the catalog.
const USERCONFIG_FIELDS = ['type', 'title', 'description', 'default', 'options', 'sensitive', 'required', 'min', 'max', 'multiple']
function strip(o) {
  return Object.fromEntries(Object.entries(o).filter(([k]) => USERCONFIG_FIELDS.includes(k)))
}

// A text in both languages: { en, de }; without a German version the English one is used.
const both = (o, k) => ({ en: o[k] ?? '', de: o[k + '_de'] ?? o[k] ?? '' })

// ---------------------------------------------------------------- Sources

// "owner/repo", GitHub links (also .../tree/<ref>/<path>) or any git URL.
export function parseLink(link) {
  const s = String(link).trim()
  if (/^[\w.-]+\/[\w.-]+$/.test(s)) return { clone: `https://github.com/${s}.git`, ref: null, sub: '' }
  const gh = /^https?:\/\/github\.com\/([\w.-]+)\/([\w.-]+?)(?:\.git)?(?:\/(?:tree|blob)\/([^/]+)(?:\/(.*))?)?\/?$/.exec(s)
  if (gh) return { clone: `https://github.com/${gh[1]}/${gh[2]}.git`, ref: gh[3] ?? null, sub: (gh[4] ?? '').replace(/\/$/, '') }
  return { clone: s, ref: null, sub: '' }
}

function git(argv, cwd) {
  try {
    // Allow long paths (Windows: 260 chars), don't rewrite line endings.
    return execFileSync('git', ['-c', 'core.longpaths=true', '-c', 'core.autocrlf=false', ...argv], { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 300_000 })
  } catch (err) {
    const why = String(err.stderr ?? '').trim().split('\n').filter(l => /fatal|error/i.test(l)).pop() ?? String(err.message ?? err).split('\n')[0]
    throw new Error(`git ${argv[0]}: ${why}`)
  }
}

// Short, unique folder name for the cache: repo name plus a hash of the link.
function cacheName(clone, ref) {
  const name = clone.replace(/\.git$/, '').split(/[\\/:]/).filter(Boolean).pop() ?? 'repo'
  const hash = createHash('sha1').update(clone + '@' + (ref ?? '')).digest('hex').slice(0, 8)
  return `${slug(name).slice(0, 30)}-${hash}`
}

// Clones (or updates) a link into the cache; returns the folder (with subpath).
function fetchLink(link, refresh) {
  return fetchParsed(parseLink(link), refresh)
}

function fetchParsed({ clone, ref, sub }, refresh) {
  const dir = path.join(CACHE, cacheName(clone, ref))
  if (!fs.existsSync(path.join(dir, '.git'))) {
    fs.mkdirSync(CACHE, { recursive: true })
    git(['clone', '--depth', '1', ...(ref ? ['--branch', ref] : []), clone, dir])
  } else if (refresh) {
    // The cache belongs to the box alone: fetch the latest state and hard-reset to it
    // (a "pull" fails on shallow clones once the original has moved on).
    git(['fetch', '--depth', '1', 'origin', ref ?? 'HEAD'], dir)
    git(['reset', '--hard', '--quiet', 'FETCH_HEAD'], dir)
  }
  const full = sub ? path.join(dir, sub) : dir
  if (!fs.existsSync(full)) throw new Error(t(`Pfad ${sub} gibt es in ${clone} nicht`, `path ${sub} does not exist in ${clone}`))
  return full
}

function pluginInfo(dir) {
  const pj = path.join(dir, '.claude-plugin', 'plugin.json')
  if (!fs.existsSync(pj)) return null
  const p = readJson(pj)
  let modules = []
  const hj = path.join(dir, 'hooks', 'hooks.json')
  if (fs.existsSync(hj)) {
    try {
      modules = readJson(hj).modules ?? []
    } catch {
      modules = []
    }
  }
  const extras = ['skills', 'agents', 'commands'].filter(d => fs.existsSync(path.join(dir, d)))
  if (p.mcpServers || fs.existsSync(path.join(dir, '.mcp.json'))) extras.push('mcp')
  return { name: p.name, description: p.description ?? '', version: p.version ?? '', isMod: modules.length > 0, extras, dir }
}

function findPlugins(dir, depth = 0, out = []) {
  if (depth > 4) return out
  const info = pluginInfo(dir)
  if (info) {
    out.push(info)
    return out
  }
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory() && !SKIP_DIRS.has(e.name) && !e.name.startsWith('.')) findPlugins(path.join(dir, e.name), depth + 1, out)
  }
  return out
}

// A marketplace folder (with marketplace.json) or a repo with one or more plugins.
function scan(dir) {
  const mp = path.join(dir, '.claude-plugin', 'marketplace.json')
  if (fs.existsSync(mp)) {
    const m = readJson(mp)
    return {
      name: m.name ?? path.basename(dir),
      plugins: (m.plugins ?? []).map(p => {
        const src = p.source
        if (typeof src === 'string') {
          const local = path.resolve(dir, src)
          const info = fs.existsSync(local) ? pluginInfo(local) : null
          return { name: p.name, description: p.description ?? info?.description ?? '', isMod: info ? info.isMod : null, extras: info?.extras ?? [], dir: info ? local : null, remote: null }
        }
        return { name: p.name, description: p.description ?? '', isMod: null, extras: [], dir: null, remote: remoteOf(src) }
      }),
    }
  }
  return { name: path.basename(dir), plugins: findPlugins(dir).map(p => ({ ...p, remote: null })) }
}

function remoteOf(src) {
  if (!src || typeof src !== 'object') return null
  if (src.source === 'github' && src.repo) return { link: `https://github.com/${src.repo}`, ref: src.ref ?? null, path: src.path ?? '' }
  if (src.url) return { link: src.url, ref: src.ref ?? null, path: src.path ?? '' }
  return null
}

function importedIds() {
  const k = readJson(BOX)
  return Object.fromEntries(k.mods.map(m => [m.upstream ?? m.id, m.id]))
}

function catalog(a) {
  const imported = importedIds()
  const sources = []
  const known = path.join(os.homedir(), '.claude', 'plugins', 'known_marketplaces.json')
  if (fs.existsSync(known)) {
    for (const [name, m] of Object.entries(readJson(known))) {
      if (name === readJson(BOX).plugin) continue
      const dir = m.installLocation
      const link = m.source?.repo ? `https://github.com/${m.source.repo}` : m.source?.url ?? m.source?.path ?? ''
      try {
        sources.push({ kind: 'claude', name, link, dir, ...decorate(scan(dir), imported) })
      } catch (err) {
        sources.push({ kind: 'claude', name, link, dir, plugins: [], error: String(err.message ?? err) })
      }
    }
  }
  for (const link of a.url) {
    try {
      const dir = fetchLink(link, a.refresh === true)
      const s = scan(dir)
      sources.push({ kind: 'link', link, dir, ...decorate(s, imported) })
    } catch (err) {
      sources.push({ kind: 'link', link, name: link, dir: null, plugins: [], error: String(err.message ?? err).split('\n')[0] })
    }
  }
  return { ok: true, sources }
}

function decorate(s, imported) {
  return { name: s.name, plugins: s.plugins.map(p => ({ ...p, imported: imported[p.name] ?? null })) }
}

